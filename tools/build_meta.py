def url_for(rel: str) -> str:
    if rel == "index.html":
        return SITE
    if rel.endswith("/index.html"):
        return SITE + rel[: -len("index.html")]
    return SITE + rel


def _crumbs(items) -> list[dict]:
    out = [{"@type": "ListItem", "position": 1, "name": "Zone2", "item": SITE}]
    for i, (href, name) in enumerate(items, start=2):
        out.append({"@type": "ListItem", "position": i, "name": name, "item": url_for(href)})
    return out


def block(rel: str, spec: dict) -> str:
    url = url_for(rel)
    graph = [
        {
            "@type": "WebSite",
            "@id": SITE + "#website",
            "url": SITE,
            "name": "Zone2",
            "inLanguage": "en",
            "publisher": {"@id": SITE + "#publisher"},
        },
        ORG,
        {
            "@type": spec["kind"],
            "@id": url + "#webpage",
            "url": url,
            "name": spec["name"],
            "description": spec["description"],
            "isPartOf": {"@id": SITE + "#website"},
            "inLanguage": "en",
        },
        {
            "@type": "BreadcrumbList",
            "@id": url + "#breadcrumb",
            "itemListElement": _crumbs(spec["crumbs"]),
        },
    ]
    payload = json.dumps({"@context": "https://schema.org", "@graph": graph}, ensure_ascii=False, indent=None)
    payload = payload.replace("</", "<\\/")
    return (
        f"{BEGIN}\n"
        f'<link rel="canonical" href="{html.escape(url, quote=True)}">\n'
        f'<meta property="og:type" content="website">\n'
        f'<meta property="og:site_name" content="Zone2">\n'
        f'<meta property="og:title" content="{html.escape(spec["name"], quote=True)}">\n'
        f'<meta property="og:description" content="{html.escape(spec["description"], quote=True)}">\n'
        f'<meta property="og:url" content="{html.escape(url, quote=True)}">\n'
        f'<meta name="twitter:card" content="summary">\n'
        f'<script type="application/ld+json">{payload}</script>\n'
        f"{END}"
    )


MARKER_BLOCK = re.compile(re.escape(BEGIN) + r".*?" + re.escape(END), re.S)
OWNED_CANONICAL = re.compile(r'\n<link rel="canonical" href="[^"]*">')


def rewrite(text: str, rel: str) -> str:
    spec = PAGES[rel]
    new_block = block(rel, spec)
    if MARKER_BLOCK.search(text):
        return MARKER_BLOCK.sub(lambda _m: new_block, text, count=1)
    # First run: insert immediately before </head>, and take ownership of any
    # canonical link that is already there so two never coexist.
    text = OWNED_CANONICAL.sub("", text)
    if "</head>" not in text:
        raise SystemExit(f"{rel}: no </head> to insert before")
    return text.replace("</head>", new_block + "\n</head>", 1)


def block_for(text: str, rel: str) -> str:
    """Public entry point for tools/page_meta.py: the page text with the head layer applied."""
    if rel not in PAGES:
        raise KeyError(
            f"{rel!r} has no entry in tools/build_meta.PAGES, so it cannot carry the generated "
            "head layer. Add the page's kind/name/description there rather than inlining meta tags."
        )
    return rewrite(text, rel)


def main(argv=None) -> int:
    argv = sys.argv[1:] if argv is None else argv
    check = "--check" in argv
    stale, written = [], 0
    for rel in PAGES:
        path = REPO / rel
        if not path.is_file():
            print(f"MISSING {rel}")
            return 1
        old = path.read_text(encoding="utf-8")
        new = rewrite(old, rel)
        if new != old:
            stale.append(rel)
            if not check:
                path.write_text(new, encoding="utf-8")
                written += 1
    print(json.dumps({"pages": len(PAGES), "stale": stale, "written": written}, indent=2))
    return 1 if (check and stale) else 0


if __name__ == "__main__":
    raise SystemExit(main())
