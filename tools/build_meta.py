#!/usr/bin/env python3
"""Add the machine-readable layer to the hand-written root pages, idempotently.

Why this exists
---------------
The root dashboard and its subpages are hand-written HTML, and they carry no
canonical URL and no structured data at all, while the generated marketing set
carries both. A search engine therefore receives two different descriptions of
the same publisher depending on which surface it enters through.

Editing thirteen hand-written <head> blocks by hand would be thirteen chances to
drift, and would collide with any other session that touches those files. So the
work is done by a generator with three properties:

  * **Idempotent.** Running it twice changes nothing: the block it inserts is
    delimited by marker comments and replaced wholesale, never appended twice.
  * **Non-destructive.** It touches only what sits between its own markers, plus
    one <link rel="canonical"> it owns. Everything a human wrote is left alone.
  * **Checked.** `--check` exits non-zero when a committed page differs from what
    a fresh run would produce, so CI fails on drift exactly like every other
    generator in this repository.

What it emits, and why only this
--------------------------------
WebSite + Organization + BreadcrumbList + WebPage on every root page, and
CollectionPage instead of WebPage where the page is a list. It deliberately
emits **no** Product, Review, AggregateRating or Offer markup: the project has
tested nothing, has no rating, and may not display a price (see
discovery/findings.html DG-06, DG-07 and discovery/sources.html S49, S59).
Structured data that describes content a reader cannot see is a guidelines
violation, so the gate below also refuses it.

Run: python3 tools/build_meta.py [--check]
"""

